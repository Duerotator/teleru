# In C++, a string literal is "(?:\\.|[^"\\])*"
CPP_STRING_LITERAL = r'"(?:\\.|[^"\\])*"'
CPP_CONCAT_STRINGS = rf'{CPP_STRING_LITERAL}(?:\s*{CPP_STRING_LITERAL})*'

DESC_PATTERN = re.compile(rf'(\.description\s*=\s*){CPP_CONCAT_STRINGS}')
NAME_PATTERN = re.compile(rf'(\.name\s*=\s*){CPP_CONCAT_STRINGS}')

def fix_prepare_script(tdesktop: Path):
    prepare_py = tdesktop / "Telegram" / "build" / "prepare" / "prepare.py"
    if prepare_py.is_file():
        text = prepare_py.read_text(encoding="utf-8")
        if "mingw-w64-x86_64-diffutils" in text:
            text = text.replace("mingw-w64-x86_64-diffutils", "diffutils")
            prepare_py.write_text(text, encoding="utf-8", newline="\n")
            print("Fixed prepare.py: replaced mingw-w64-x86_64-diffutils with diffutils.")

def fix_updater_file(path: Path):
    if not path.is_file():
        print(f"Warning: {path} not found.")
        return
    text = path.read_text(encoding="utf-8")

    # 1. Repoint feed and download URLs to Duerotator/teleru
    feed_pat = re.compile(r'constexpr auto kFeedUrlPrefix = [^;]+;')
    dl_pat = re.compile(r'constexpr auto kDownloadPrefix = [^;]+;')

    new_feed = 'constexpr auto kFeedUrlPrefix = "https://github.com/Duerotator/teleru/releases/"\n\t"latest/download/tele-update-";'
    new_dl = 'constexpr auto kDownloadPrefix = "https://github.com/Duerotator/teleru/"\n\t"releases/download/";'

    text, n1 = feed_pat.subn(new_feed, text, count=1)
    text, n2 = dl_pat.subn(new_dl, text, count=1)

    # 2. Allow unsigned or self-published feed
    target_sig = 'if (!Core::Updates::VerifySignature(key, feed, signature, &error)) {'
    repl_sig = 'if (!signature.isEmpty() && !Core::Updates::VerifySignature(key, feed, signature, &error)) {'
    if target_sig in text:
        text = text.replace(target_sig, repl_sig, 1)

    target_feed = 'const auto feed = QByteArray::fromBase64(\n\t\touter.value(u"feed"_q).toString().toLatin1());'
    repl_feed = 'const auto feedStr = outer.value(u"feed"_q).toString();\n\tconst auto feed = feedStr.isEmpty() ? envelope : QByteArray::fromBase64(feedStr.toLatin1());'
    if target_feed in text:
        text = text.replace(target_feed, repl_feed, 1)

    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"tele_updater.cpp: Updated feed URLs to Duerotator/teleru (feed: {n1}, dl: {n2}).")

def translate_options_file(path: Path):
    if not path.is_file():
        print(f"Warning: {path} not found.")
        return

    text = path.read_text(encoding="utf-8")
    count_names = 0
    count_descs = 0

    for opt_id, data in OPTIONS_RU.items():
        idx = text.find(f'.id = {opt_id}')
        if idx == -1:
            continue
        start = text.rfind('base::options::', 0, idx)
        end = text.find('});', idx)
        if start == -1 or end == -1:
            continue
        end += 3
        block = text[start:end]
        new_block = block

        ru_name = data.get("name")
        if ru_name:
            new_block, n = NAME_PATTERN.subn(lambda m: m.group(1) + f'"{ru_name}"', new_block)
            if n > 0:
                count_names += n

        ru_desc = data.get("desc")
        if ru_desc:
            new_block, n = DESC_PATTERN.subn(lambda m: m.group(1) + f'"{ru_desc}"', new_block)
            if n > 0:
                count_descs += n

        if new_block != block:
            text = text.replace(block, new_block, 1)

    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"tele_options.cpp: Translated {count_names} option names and {count_descs} descriptions.")

def translate_settings_file(path: Path):
    if not path.is_file():
        print(f"Warning: {path} not found.")
        return
    text = path.read_text(encoding="utf-8")

    count_groups = 0
    for eng_title, ru_title in GROUP_TITLES_RU.items():
        pattern = rf'AddGroupTitle\(builder,\s*u"{re.escape(eng_title)}"_q\)'
        replacement = f'AddGroupTitle(builder, u"{ru_title}"_q)'
        new_text, n = re.subn(pattern, replacement, text)
        if n > 0:
            count_groups += n
            text = new_text

    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"settings_tele.cpp: Translated {count_groups} group titles.")

def translate_all_sources(source_dir: Path):
    if not source_dir.is_dir():
        print(f"Warning: {source_dir} is not a directory.")
        return

    # Prepare C++ escaped replacements
    replacements = []
    for eng, ru in MASTER_DICT.items():
        if not eng.strip():
            continue
        cpp_eng = eng.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
        cpp_ru = ru.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')

        replacements.append((f'u"{cpp_eng}"_q', f'u"{cpp_ru}"_q'))
        replacements.append((f'QStringLiteral("{cpp_eng}")', f'QStringLiteral("{cpp_ru}")'))
        replacements.append((f'_q("{cpp_eng}")', f'_q("{cpp_ru}")'))

    # Sort replacements by length of target string descending to avoid substring partial replacements
    replacements.sort(key=lambda x: len(x[0]), reverse=True)

    # Search in all tele source directories and common UI directories
    scan_subdirs = ["tele", "settings", "dialogs", "window", "history", "info", "intro", "boxes"]
    target_files = []
    for sub in scan_subdirs:
        d = source_dir / sub
        if d.is_dir():
            for f in d.rglob("*"):
                if f.is_file() and (f.suffix in [".cpp", ".h", ".mm"]):
                    target_files.append(f)

    print(f"Scanning {len(target_files)} C++ source files for Russian translations...")
    total_replacements = 0
    modified_files = 0

    for file_path in target_files:
        try:
            text = file_path.read_text(encoding="utf-8")
        except Exception:
            continue

        file_replacements = 0
        new_text = text
        for old_str, new_str in replacements:
            if old_str in new_text:
                c = new_text.count(old_str)
                new_text = new_text.replace(old_str, new_str)
                file_replacements += c

        if file_replacements > 0:
            file_path.write_text(new_text, encoding="utf-8", newline="\n")
            total_replacements += file_replacements
            modified_files += 1

    print(f"Global translation: Applied {total_replacements} translations across {modified_files} source files.")

def main():
    if len(sys.argv) < 2:
        print("Usage: python translate_ru.py <path_to_tdesktop>")
        sys.exit(1)

    tdesktop = Path(sys.argv[1]).resolve()
    print(f"Localizing tele to Russian in: {tdesktop}")

    source_dir = tdesktop / "Telegram" / "SourceFiles"

    fix_prepare_script(tdesktop)
    fix_updater_file(source_dir / "tele" / "tele_updater.cpp")

    translate_options_file(source_dir / "tele" / "tele_options.cpp")
    translate_settings_file(source_dir / "settings" / "settings_tele.cpp")
    translate_all_sources(source_dir)

    print("Complete 100% Russian localization and permanent update protection applied successfully!")

if __name__ == "__main__":
    main()
